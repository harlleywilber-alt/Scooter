-- =====================================================================
-- E-Scooter GO - Esquema relacional (PostgreSQL 13+)
--
-- Este arquivo é aplicado automaticamente pelo servidor na inicialização
-- (server/inicializacao.js). Todos os comandos são idempotentes, então
-- também pode ser executado manualmente no pgAdmin/psql sem risco.
--
-- Convenções:
--  * IDs gerados pelo banco (IDENTITY), nunca calculados no Node.
--  * Dinheiro em NUMERIC(10,2) (sem erro de arredondamento de float).
--  * Datas em TIMESTAMPTZ (instante absoluto; relatórios convertem para o
--    fuso da operação com AT TIME ZONE).
--  * Locações e manutenções guardam uma "foto" (código do patinete, nome do
--    ponto, login do operador) do momento em que ocorreram: o histórico
--    financeiro continua correto mesmo se o patinete/ponto for removido ou
--    renomeado depois. As chaves estrangeiras ficam como ON DELETE SET NULL.
-- =====================================================================

CREATE TABLE IF NOT EXISTS pontos (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome         VARCHAR(100) NOT NULL,
  localizacao  VARCHAR(180) NOT NULL DEFAULT 'Sem localização',
  criado_em    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS usuarios (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome             VARCHAR(100) NOT NULL,
  usuario          VARCHAR(40)  NOT NULL,
  senha_hash       VARCHAR(128) NOT NULL,
  salt             VARCHAR(64)  NOT NULL,
  iteracoes_senha  INTEGER      NOT NULL DEFAULT 120000,
  cargo            VARCHAR(60)  NOT NULL DEFAULT 'Operador',
  nivel            VARCHAR(20)  NOT NULL DEFAULT 'operador'
                   CHECK (nivel IN ('administrador', 'operador')),
  status           VARCHAR(20)  NOT NULL DEFAULT 'pendente'
                   CHECK (status IN ('pendente', 'aprovado', 'recusado')),
  bloqueado        BOOLEAN      NOT NULL DEFAULT false,
  ponto_id         INTEGER      REFERENCES pontos(id) ON DELETE SET NULL,
  ultimo_login     TIMESTAMPTZ,
  ultima_atividade TIMESTAMPTZ,
  criado_em        TIMESTAMPTZ  NOT NULL DEFAULT now()
);
-- Login único sem diferenciar maiúsculas/minúsculas ("Admin" = "admin")
CREATE UNIQUE INDEX IF NOT EXISTS usuarios_login_unico ON usuarios (lower(usuario));

CREATE TABLE IF NOT EXISTS patinetes (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo     VARCHAR(20) NOT NULL UNIQUE,
  modelo     VARCHAR(60) NOT NULL DEFAULT 'E-Scooter Pro Max',
  bateria    SMALLINT    NOT NULL DEFAULT 100 CHECK (bateria BETWEEN 0 AND 100),
  status     VARCHAR(20) NOT NULL DEFAULT 'livre'
             CHECK (status IN ('livre', 'locado', 'manutencao')),
  ponto_id   INTEGER     REFERENCES pontos(id) ON DELETE SET NULL,
  criado_em  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS patinetes_ponto ON patinetes (ponto_id);

CREATE TABLE IF NOT EXISTS clientes (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome             VARCHAR(100) NOT NULL,
  telefone         VARCHAR(20)  NOT NULL DEFAULT '',
  -- Só os dígitos do telefone: identifica o cliente ("(62) 9999-0000" = "6299990000")
  telefone_digitos VARCHAR(20)  UNIQUE,
  criado_em        TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS locacoes (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patinete_id      INTEGER REFERENCES patinetes(id) ON DELETE SET NULL,
  patinete_codigo  VARCHAR(20)   NOT NULL,
  cliente_id       INTEGER NOT NULL REFERENCES clientes(id),
  ponto_id         INTEGER REFERENCES pontos(id) ON DELETE SET NULL,
  ponto_nome       VARCHAR(100)  NOT NULL DEFAULT 'Sem ponto',
  operador_id      INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  operador_usuario VARCHAR(40)   NOT NULL,
  tempo_minutos    INTEGER       NOT NULL CHECK (tempo_minutos BETWEEN 1 AND 1440),
  valor_base       NUMERIC(10,2) NOT NULL CHECK (valor_base >= 0),
  multa            NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (multa >= 0),
  valor_total      NUMERIC(10,2) GENERATED ALWAYS AS (valor_base + multa) STORED,
  pagamento        VARCHAR(30)   NOT NULL
                   CHECK (pagamento IN ('Pix', 'Cartão de Crédito', 'Cartão de Débito', 'Dinheiro')),
  status           VARCHAR(20)   NOT NULL DEFAULT 'ativa'
                   CHECK (status IN ('ativa', 'finalizada', 'cancelada')),
  data_inicio      TIMESTAMPTZ   NOT NULL DEFAULT now(),
  data_fim         TIMESTAMPTZ,
  CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);
-- O próprio banco impede duas locações ativas do mesmo patinete
CREATE UNIQUE INDEX IF NOT EXISTS locacoes_uma_ativa_por_patinete
  ON locacoes (patinete_id) WHERE status = 'ativa';
CREATE INDEX IF NOT EXISTS locacoes_data_inicio ON locacoes (data_inicio);
CREATE INDEX IF NOT EXISTS locacoes_cliente ON locacoes (cliente_id);

CREATE TABLE IF NOT EXISTS manutencoes (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patinete_id         INTEGER REFERENCES patinetes(id) ON DELETE SET NULL,
  patinete_codigo     VARCHAR(20)   NOT NULL,
  ponto_id            INTEGER REFERENCES pontos(id) ON DELETE SET NULL,
  ponto_nome          VARCHAR(100)  NOT NULL DEFAULT 'Sem ponto',
  usuario_id          INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  usuario_login       VARCHAR(40)   NOT NULL,
  descricao           VARCHAR(300)  NOT NULL,
  prioridade          VARCHAR(10)   NOT NULL DEFAULT 'media'
                      CHECK (prioridade IN ('baixa', 'media', 'urgente')),
  diagnostico         VARCHAR(500)  NOT NULL DEFAULT '',
  responsavel_servico VARCHAR(120)  NOT NULL DEFAULT '',
  previsao_conclusao  TIMESTAMPTZ,
  valor               NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (valor BETWEEN 0 AND 100000),
  status              VARCHAR(20)   NOT NULL DEFAULT 'em_manutencao'
                      CHECK (status IN ('em_manutencao', 'concluida')),
  data                TIMESTAMPTZ   NOT NULL DEFAULT now(),
  data_liberacao      TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS manutencoes_patinete ON manutencoes (patinete_id);
CREATE INDEX IF NOT EXISTS manutencoes_data ON manutencoes (data);

CREATE TABLE IF NOT EXISTS historico_usuarios (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  acao          VARCHAR(40)  NOT NULL,
  usuario_id    INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  usuario_nome  VARCHAR(100) NOT NULL,   -- mantido mesmo se o usuário for excluído
  responsavel   VARCHAR(40)  NOT NULL DEFAULT 'sistema',
  detalhes      TEXT         NOT NULL DEFAULT '',
  data          TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS historico_usuarios_data ON historico_usuarios (data DESC);

-- Configuração geral: tabela de uma linha só (id sempre 1)
CREATE TABLE IF NOT EXISTS configuracoes (
  id                       SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  nome_admin               VARCHAR(100)  NOT NULL DEFAULT 'Administrador Geral',
  cargo_admin              VARCHAR(100)  NOT NULL DEFAULT 'Gestor do Sistema',
  nome_empresa             VARCHAR(100)  NOT NULL DEFAULT 'E-Scooter Go',
  multa_por_minuto         NUMERIC(10,2) NOT NULL DEFAULT 1 CHECK (multa_por_minuto >= 0),
  limite_patinetes_locacao SMALLINT      NOT NULL DEFAULT 5 CHECK (limite_patinetes_locacao BETWEEN 1 AND 20),
  alerta_manutencao_dias   SMALLINT      NOT NULL DEFAULT 3 CHECK (alerta_manutencao_dias >= 1)
);

-- Tabela de preços: cada linha é um tempo de locação disponível
CREATE TABLE IF NOT EXISTS precos (
  tempo_minutos INTEGER PRIMARY KEY CHECK (tempo_minutos BETWEEN 1 AND 1440),
  valor         NUMERIC(10,2) NOT NULL CHECK (valor > 0)
);
